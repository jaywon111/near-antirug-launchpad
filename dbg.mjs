import { DEFAULT_ACCOUNT_ID, DEFAULT_PRIVATE_KEY } from 'near-sandbox';
import * as nearAPI from 'near-api-js';
import fs from 'fs';
const rpc = fs.readFileSync('/tmp/sandbox_rpc','utf8').trim();
const keyStore = new nearAPI.keyStores.InMemoryKeyStore();
await keyStore.setKey('sandbox', DEFAULT_ACCOUNT_ID, nearAPI.utils.KeyPair.fromString(DEFAULT_PRIVATE_KEY));
const near = await nearAPI.connect({ networkId:'sandbox', nodeUrl: rpc, keyStore });
const owner = await near.account(DEFAULT_ACCOUNT_ID);
const wasm = fs.readFileSync('contract/target/wasm32-unknown-unknown/release/near_antirug_launchpad_contract.wasm');
const cid = 'dbg'+Date.now()+'.sandbox';
const kp = nearAPI.utils.KeyPair.fromRandom('ed25519');
await owner.createAndDeployContract(cid, kp.publicKey, wasm, nearAPI.utils.format.parseNearAmount('20'));
const c = owner; const contract = new nearAPI.Contract(c, cid, { changeMethods:['new','create_token','buy'], viewMethods:['get_launch','get_balance'] });
await contract.new();
await contract.create_token({name:'TT',symbol:'TT',supply:'1000000',initial_reserve:'10000000',base_price:'100',slope:'10000',dev_vesting_bps:2000,vesting_cliff_ns:100,vesting_duration_ns:1000}, undefined, nearAPI.utils.format.parseNearAmount('0.05'));
console.log('created');
const r = await contract.buy({ token_id:'launch-1', amount:'10', min_out:'1' }, undefined, nearAPI.utils.format.parseNearAmount('0.1'));
console.log('buy return:', JSON.stringify(r));
const l = await contract.get_launch({token_id:'launch-1'});
console.log('circulating:', l.circulating, 'reserve:', l.locked_reserve);
console.log('creator balance (contract):', JSON.stringify(await contract.get_balance({token_id:'launch-1', account_id: cid})));
console.log('predecessor echo? creator:', l.creator);
console.log('balance for', DEFAULT_ACCOUNT_ID, ':', JSON.stringify(await contract.get_balance({token_id:'launch-1', account_id: DEFAULT_ACCOUNT_ID})));
process.exit(0);
